import streamlit as st

from models.gui_services import (
    dataset_counts,
    evaluation_data,
    evaluation_metrics,
    model_evaluation_matrix,
    model_statuses,
    session_statistics,
)


st.markdown(
    """
    <div style="padding:1.6rem 1.8rem; margin-bottom:1rem; border-radius:22px;
        background:linear-gradient(120deg,#e9f5f4 0%,#eef5fb 100%);
        border:1px solid #dcebea;">
      <div style="font-size:.76rem; text-transform:uppercase; letter-spacing:.12em;
          font-weight:700; color:#167d78;">Prescription workspace</div>
      <h1 style="margin:.5rem 0 .35rem; color:#19383c;">Handwriting review, made clearer</h1>
      <p style="max-width:720px; margin:0; color:#587579;">
        Upload a prescription image or PDF, run handwriting recognition, then
        compare and correct the result against the original.
      </p>
    </div>
    """,
    unsafe_allow_html=True,
)
action_columns = st.columns([1, 1, 2])
action_columns[0].page_link(
    "pages/2_Prescription_Analyzer.py",
    label="Analyze a prescription",
    icon=":material/document_scanner:",
    use_container_width=True,
)
action_columns[1].page_link(
    "pages/5_Results_Verification.py",
    label="Review results",
    icon=":material/fact_check:",
    use_container_width=True,
)
with action_columns[2]:
    st.warning(
        "For transcription assistance only. This app does not provide medical "
        "advice; a qualified reviewer must verify every result."
    )

st.subheader("Workspace activity")
stats = session_statistics()
stat_columns = st.columns(4)
stat_columns[0].metric("Analysis runs", int(stats["runs"]))
stat_columns[1].metric("Pages processed", int(stats["pages"]))
stat_columns[2].metric("Successful pages", int(stats["successful_pages"]))
stat_columns[3].metric("Pages with errors", int(stats["failed_pages"]))

with st.expander("Project dataset counts", expanded=False):
    st.caption("Label rows available in the local project dataset.")
    try:
        counts = dataset_counts()
    except (OSError, ValueError) as exc:
        st.warning(f"Dataset label counts are unavailable: {exc}")
    else:
        dataset_columns = st.columns(2)
        for column, split in zip(dataset_columns, ("train", "test")):
            count = counts[split]
            column.metric(
                f"{split.title()} label rows",
                f"{count:,}" if count is not None else "Unavailable",
            )

st.subheader("Available models")
models = model_statuses()
model_columns = st.columns(len(models))
for column, model in zip(model_columns, models):
    with column.container(border=True):
        st.markdown(f"**{model['name']}**")
        st.write(model["purpose"])
        if model["available"]:
            st.success("Checkpoint available")
        else:
            st.warning("Checkpoint not found")

st.subheader("Handwriting-recognition performance")
try:
    data = evaluation_data()
    metrics = evaluation_metrics(data)
except (FileNotFoundError, OSError, ValueError, ImportError) as exc:
    st.warning(f"Existing evaluation metrics are unavailable: {exc}")
else:
    columns = st.columns(4)
    columns[0].metric(
        "Case-insensitive exact match",
        f"{metrics['exact_match_percent']:.2f}%",
        help="Measured over the saved TrOCR test-set predictions.",
    )
    columns[1].metric("Mean per-record CER", f"{metrics['mean_cer']:.2%}")
    columns[2].metric("Mean per-record WER", f"{metrics['mean_wer']:.2%}")
    columns[3].metric(
        "Recorded mean inference time",
        f"{metrics['mean_inference_seconds']:.2f} s/image",
    )
    st.caption(
        f"Saved evaluation rows: {metrics['samples']:,}. "
        f"Corpus CER: {metrics['corpus_cer']:.2%}; "
        f"corpus WER: {metrics['corpus_wer']:.2%}. "
        "Recorded generation time per image; not end-to-end upload time."
    )
    with st.expander("Evaluation matrix", expanded=False):
        st.dataframe(
            model_evaluation_matrix(metrics),
            width="stretch",
            hide_index=True,
        )
        st.caption(
            "Only TrOCR has saved handwriting-recognition measurements. "
            "AE/VAE are reconstruction models and are not scored as OCR."
        )

st.subheader("Synthetic data")
synthetic_columns = st.columns([3, 1])
synthetic_columns[0].markdown(
    """
    **Fictional records generated by the local GAN**  
    Open the lab to generate placeholder-only synthetic samples. They are not
    real prescriptions and must never be used for medical decisions.
    """
)
synthetic_columns[1].page_link(
    "pages/6_Synthetic_Record_Lab.py",
    label="Open synthetic lab",
    icon=":material/auto_awesome:",
    use_container_width=True,
)
